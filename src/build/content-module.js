// generatedModules provider "openchara-content": the engine's content.generated.js (as the virtual module
// @openrock/virtual/openchara-content), automatic portraits, and the character's render controller.
"use strict";

const path = require("path");
const { loadProjectContent } = require("./project.js");
const { walk } = require("./content.js");

module.exports = ctx => {
    const { p, content } = loadProjectContent(ctx.mod, ctx.modDir);
    const rp = {};

    // Automatic portraits (MinUI) before the module is rendered, since the module carries their paths.
    const minuiDir = path.resolve(ctx.dir, ctx.manifest.dependsOn["@minui/core"].path);
    const { generatePortraits } = require(path.join(minuiDir, "lib", "portraits.js"));
    const portraits = generatePortraits(p, content.characters, walk);
    for (const [rel, buf] of portraits.files) rp[rel] = buf;
    for (const [id, pp] of Object.entries(portraits.paths)) {
        content.characters[id].portrait ??= pp.portrait;
        content.characters[id].bust ??= pp.bust;
    }

    const config = {
        name: p.name,
        namespace: p.namespace,
        characterKey: p.character.key,
        nouns: p.character.nouns,
        chatTag: p.chatTag,
        devTools: p.devTools,
        navigationSlots: p.navigationSlots,
        rules: p.rules ?? {},
    };
    const j = v => JSON.stringify(v, null, 2);
    const source = `// GENERATED by OpenChara build from ${p.name}'s PATCHES - do not edit.\n` +
        `export const CONFIG = ${j(config)};\n` +
        `export const CHARACTERS = ${j(content.characters)};\n` +
        `export const CLASSES = ${j(content.classes)};\n` +
        `export const ABILITIES = ${j(content.abilities)};\n` +
        `export const QUESTS = ${j(content.quests)};\n` +
        `export const SCHEMA = ${j(content.schema)};\n`;

    // Render controller: one texture array slot per character index (a gap renders the lowest-index character).
    const ns = p.namespace, key = p.character.key;
    const chars = Object.values(content.characters);
    const first = [...chars].sort((a, b) => a.index - b.index)[0];
    const maxIndex = Math.max(0, ...chars.map(c => c.index));
    const arr = [];
    for (let i = 0; i <= maxIndex; i++) arr.push(`Texture.species${chars.some(c => c.index === i) ? i : first?.index ?? 0}`);
    rp[`render_controllers/${key}.render_controllers.json`] = JSON.stringify({
        format_version: "1.10.0",
        render_controllers: {
            [`controller.render.${ns}_${key}`]: {
                arrays: { textures: { [`Array.${ns}_species`]: arr } },
                geometry: "Geometry.default",
                materials: [{ "*": "Material.default" }],
                textures: [`Array.${ns}_species[q.property('${ns}:species_index')]`],
            },
        },
    }, null, 2) + "\n";

    return { source, rp };
};
