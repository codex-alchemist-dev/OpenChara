// generatedModules provider "ghost-table": block id -> ghost texture index, as the virtual module
// @openrock/virtual/ghost-table (read by engine/scripts/openchara/build/ghostEntities.js through a shim).
"use strict";

const { loadAppearance, indexTable } = require("./blockAppearance.js");

module.exports = ctx => {
    const appearance = loadAppearance({ modDir: ctx.modDir, packages: ctx.packages, extraDirs: ctx.mod.openchara?.ghostSources ?? [] });
    return `// GENERATED by OpenChara build from Minecraft's block data and your packs - do not edit.\nexport const GHOST_INDEX = ${JSON.stringify(indexTable(appearance))};\n`;
};
